#!/usr/bin/env bash
# Writes the AUR package (PKGBUILD, .SRCINFO) and the Homebrew formula
# (footui.rb) for a release, from the checksums `make release` produced.
#
#   packaging/render.sh v1.2.0 dist/SHA256SUMS dist/packaging
#
# The release workflow runs this and attaches the output to the GitHub
# release. Publishing is then a copy: the PKGBUILD and .SRCINFO into the
# footui-bin AUR repo, footui.rb into JohnSBarden/homebrew-tap's Formula/.
set -euo pipefail

tag=${1:?usage: render.sh <tag> <SHA256SUMS> <out-dir>}
sums=${2:?usage: render.sh <tag> <SHA256SUMS> <out-dir>}
out=${3:?usage: render.sh <tag> <SHA256SUMS> <out-dir>}

version=${tag#v}
# Arch and Homebrew both reject a "-" in the version (v1.2.0-rc1).
if [[ $version == *-* ]]; then
	echo "render.sh: $tag is a pre-release; not packaging it" >&2
	exit 0
fi

repo=https://github.com/JohnSBarden/footui
url=$repo/releases/download/$tag
here=$(cd "$(dirname "$0")" && pwd)

sum() {
	local s
	s=$(awk -v f="footui-$1" '$2 == f { print $1 }' "$sums")
	[[ -n $s ]] || { echo "render.sh: no checksum for footui-$1 in $sums" >&2; exit 1; }
	echo "$s"
}
linux_amd64=$(sum linux-amd64)
linux_arm64=$(sum linux-arm64)
darwin_amd64=$(sum darwin-amd64)
darwin_arm64=$(sum darwin-arm64)
license=$(sha256sum "$here/../LICENSE" | cut -d' ' -f1)

mkdir -p "$out"

cat >"$out/PKGBUILD" <<PKG
# Maintainer: JohnSBarden <13333213+JohnSBarden@users.noreply.github.com>
# Generated by footui's packaging/render.sh for $tag.
pkgname=footui-bin
pkgver=$version
pkgrel=1
pkgdesc='Football stats in the terminal: leagues, clubs, players and nations'
arch=('x86_64' 'aarch64')
url='$repo'
license=('MIT')
provides=('footui')
conflicts=('footui')
source=("LICENSE-\$pkgver::https://raw.githubusercontent.com/JohnSBarden/footui/v\$pkgver/LICENSE")
source_x86_64=("footui-\$pkgver-x86_64::$repo/releases/download/v\$pkgver/footui-linux-amd64")
source_aarch64=("footui-\$pkgver-aarch64::$repo/releases/download/v\$pkgver/footui-linux-arm64")
sha256sums=('$license')
sha256sums_x86_64=('$linux_amd64')
sha256sums_aarch64=('$linux_arm64')

package() {
	install -Dm755 "footui-\$pkgver-\$CARCH" "\$pkgdir/usr/bin/footui"
	install -Dm644 "LICENSE-\$pkgver" "\$pkgdir/usr/share/licenses/\$pkgname/LICENSE"
}
PKG

# .SRCINFO is what the AUR reads; `makepkg --printsrcinfo` would write the
# same thing, but needs an Arch box.
cat >"$out/.SRCINFO" <<SRC
pkgbase = footui-bin
	pkgdesc = Football stats in the terminal: leagues, clubs, players and nations
	pkgver = $version
	pkgrel = 1
	url = $repo
	arch = x86_64
	arch = aarch64
	license = MIT
	provides = footui
	conflicts = footui
	source = LICENSE-$version::https://raw.githubusercontent.com/JohnSBarden/footui/v$version/LICENSE
	sha256sums = $license
	source_x86_64 = footui-$version-x86_64::$url/footui-linux-amd64
	sha256sums_x86_64 = $linux_amd64
	source_aarch64 = footui-$version-aarch64::$url/footui-linux-arm64
	sha256sums_aarch64 = $linux_arm64

pkgname = footui-bin
SRC

cat >"$out/footui.rb" <<RB
# Generated by footui's packaging/render.sh for $tag.
class Footui < Formula
  desc "Football stats in the terminal: leagues, clubs, players and nations"
  homepage "$repo"
  version "$version"
  license "MIT"

  on_macos do
    on_arm do
      url "$url/footui-darwin-arm64"
      sha256 "$darwin_arm64"
    end
    on_intel do
      url "$url/footui-darwin-amd64"
      sha256 "$darwin_amd64"
    end
  end

  on_linux do
    on_arm do
      url "$url/footui-linux-arm64"
      sha256 "$linux_arm64"
    end
    on_intel do
      url "$url/footui-linux-amd64"
      sha256 "$linux_amd64"
    end
  end

  def install
    bin.install Dir["footui-*"].first => "footui"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/footui version")
  end
end
RB

echo "wrote $out/PKGBUILD, $out/.SRCINFO and $out/footui.rb for $tag"
